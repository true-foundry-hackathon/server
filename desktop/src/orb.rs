#[derive(Props, Clone, PartialEq)]
pub struct VoxLogoProps {
    #[props(default = 84)]
    pub size: u32,
    #[props(default = false)]
    pub animated: bool,
    #[props(default = OrbState::Idle)]
    pub state: OrbState,
    #[props(default = 1.0)]
    pub speed: f64,
    #[props(default = String::new())]
    pub class: String,
}

/// Vox logo: static `STATIC_ORB_DOTS` SVG, or thinking-orbs canvas when animated.
#[component]
pub fn VoxLogo(props: VoxLogoProps) -> Element {
    if props.animated {
        return rsx! {
            ThinkingOrb {
                size: props.size,
                state: props.state,
                speed: props.speed,
                class: props.class.clone(),
            }
        };
    }

    rsx! {
        VoxOrbSvg {
            size: props.size,
            class: props.class,
        }
    }
}

