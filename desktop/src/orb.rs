#[derive(Props, Clone, PartialEq)]
pub struct ThinkingOrbProps {
    #[props(default = 64)]
    pub size: u32,
    #[props(default = OrbState::Idle)]
    pub state: OrbState,
    #[props(default = 1.0)]
    pub speed: f64,
    #[props(default = String::new())]
    pub class: String,
}

#[component]
pub fn ThinkingOrb(props: ThinkingOrbProps) -> Element {
    let canvas_id = use_hook(|| {
        static NEXT: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(1);
        format!(
            "vox-orb-{}",
            NEXT.fetch_add(1, std::sync::atomic::Ordering::Relaxed)
        )
    });

    use_effect({
        let canvas_id = canvas_id.clone();
        let state = props.state.thinking_state().to_string();
        let size = props.size;
        let speed = props.speed;
        move || {
            let canvas_id = canvas_id.clone();
            let state = state.clone();
            spawn(async move {
                ensure_thinking_orb_module().await;
                let Some(window) = web_sys::window() else {
                    return;
                };
                let Some(document) = window.document() else {
                    return;
                };
                let Some(el) = document.get_element_by_id(&canvas_id) else {
                    return;
                };
                if el.dyn_ref::<web_sys::HtmlElement>().is_none() {
                    return;
                }
                let canvas: JsValue = el.clone().into();

                let opts = js_sys::Object::new();
                let _ = js_sys::Reflect::set(&opts, &"state".into(), &JsValue::from_str(&state));
                let _ =
                    js_sys::Reflect::set(&opts, &"size".into(), &JsValue::from_f64(size as f64));
                let _ = js_sys::Reflect::set(&opts, &"theme".into(), &JsValue::from_str("dark"));
                let _ = js_sys::Reflect::set(&opts, &"speed".into(), &JsValue::from_f64(speed));

                if let Ok(prev) = js_sys::Reflect::get(&canvas, &"__voxOrbUnmount".into()) {
                    if prev.is_function() {
                        let _ = js_sys::Function::from(prev).call0(&JsValue::NULL);
                    }
                }

                if js_sys::Reflect::get(&window, &"__voxMountThinkingOrb".into())
                    .ok()
                    .filter(|v| v.is_function())
                    .is_none()
                {
                    return;
                }

                let unmount = mount_thinking_orb(canvas.clone(), opts.into());
                let _ = js_sys::Reflect::set(&canvas, &"__voxOrbUnmount".into(), &unmount);
            });
        }
    });

    rsx! {
        canvas {
            id: "{canvas_id}",
            class: "thinking-orb-canvas {props.class}",
            width: "{props.size}",
            height: "{props.size}",
            style: "width: {props.size}px; height: {props.size}px; display: block;",
            role: "img",
            "aria-label": "Vox",
        }
    }
}

/// Load the thinking-orbs bundle once for the whole app.
#[component]
pub fn ThinkingOrbScript() -> Element {
    rsx! {
        script { src: THINKING_ORB_JS }
    }
}

async fn ensure_thinking_orb_module() {
    let Some(window) = web_sys::window() else {
        return;
    };
    for _ in 0..20 {
        if js_sys::Reflect::get(&window, &"__voxMountThinkingOrb".into())
            .ok()
            .filter(|v| v.is_function())
            .is_some()
        {
            return;
        }
        let promise = js_sys::Promise::new(&mut |resolve, _reject| {
            let _ = window.set_timeout_with_callback_and_timeout_and_arguments_0(&resolve, 25);
        });
        let _ = wasm_bindgen_futures::JsFuture::from(promise).await;
    }
}
