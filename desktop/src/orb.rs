/// Visual state mapped onto thinking-orbs animation presets.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum OrbState {
    #[default]
    Idle,
    Connecting,
    Active,
    Error,
}

impl OrbState {
    fn thinking_state(self) -> &'static str {
        match self {
            OrbState::Idle => "composing",
            OrbState::Connecting => "connecting",
            OrbState::Active => "listening",
            OrbState::Error => "shaping",
        }
    }
}

